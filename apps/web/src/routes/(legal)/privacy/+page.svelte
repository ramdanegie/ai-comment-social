<h1>Privacy Policy</h1>
<p class="updated">Last updated: 25 September 2026</p>

<p>
  Replyra ("Replyra", "we", "us") is an AI comment-management service operated by
  <strong>PT CREATIVE SHINE INNOVATION</strong>, Indonesia. This policy explains what data Replyra processes when a
  business connects its Instagram Professional account or Facebook Page, why, and how you can control it.
</p>

<h2>1. Data we collect</h2>
<ul>
  <li><strong>Account data:</strong> your name, email and workspace details when you sign up.</li>
  <li>
    <strong>Data from Meta (with your permission):</strong> the ID, username and profile picture of the Instagram
    Professional account or Facebook Page you connect; your posts (ID, caption, link, thumbnail); and comments on
    those posts (comment ID, text, commenter username/ID and time).
  </li>
  <li>
    <strong>Access tokens</strong> issued by Meta, stored encrypted (AES-256-GCM) and used only to call the Instagram
    and Facebook APIs on your behalf.
  </li>
  <li><strong>Technical data:</strong> IP address, browser and device information for security and diagnostics.</li>
</ul>

<h2>2. How we use the data</h2>
<ul>
  <li>Classify comments (sentiment, spam, abusive or risky content) so your team can prioritise them.</li>
  <li>Draft replies, and send replies or hide comments <strong>only according to the rules you configure</strong> or after a team member approves them.</li>
  <li>Show dashboards and reports about comments on your own accounts.</li>
  <li>Keep the service secure, prevent abuse and comply with the law.</li>
</ul>
<p>We only access accounts that you connect, and only the permissions you grant. We do not use Meta data for advertising or to build profiles of commenters.</p>

<h2>3. AI processing</h2>
<p>
  Comment text may be sent to our AI model provider to classify it and draft a reply. The provider processes it on our
  behalf and does not use it to train its models. High-risk comments are never answered automatically.
</p>

<h2>4. Sharing</h2>
<p>
  We do not sell personal data. We share it only with service providers that help us run Replyra (cloud hosting,
  database, AI model provider, email), bound by confidentiality, or when required by law.
</p>

<h2>5. Retention</h2>
<ul>
  <li>Comments and classifications: up to 12 months, then deleted.</li>
  <li>Access tokens: until you disconnect the account or revoke access in Instagram/Facebook.</li>
  <li>When you disconnect an account, its tokens, posts and comments are deleted from Replyra.</li>
</ul>

<h2>6. Security</h2>
<p>Data is encrypted in transit (HTTPS); tokens are encrypted at rest; access is limited to authorised staff and scoped per workspace.</p>

<h2>7. Your rights</h2>
<p>
  You can access, correct or delete your data, disconnect accounts at any time, and revoke Replyra's access from
  Instagram (Settings → Apps and websites) or Facebook (Settings → Business integrations). See
  <a href="/data-deletion">Data Deletion</a> for step-by-step instructions.
</p>

