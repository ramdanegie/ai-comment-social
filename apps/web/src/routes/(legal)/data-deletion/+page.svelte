<h1>Data Deletion Instructions</h1>
<p class="updated">Last updated: 25 September 2026</p>

<p>
  You can remove data that Replyra holds about you — including data received from Instagram or Facebook — at any time.
</p>

<h2>Option 1 — Disconnect in Replyra (immediate)</h2>
<ol>
  <li>Sign in to Replyra and open <strong>Connected Accounts</strong>.</li>
  <li>Click the delete icon on the Instagram account or Facebook Page and confirm.</li>
  <li>The account's access tokens, posts and comments are deleted from Replyra.</li>
</ol>

<h2>Option 2 — Remove the app from Instagram or Facebook</h2>
<ul>
  <li><strong>Instagram:</strong> Settings → Apps and websites → Active → Replyra → Remove.</li>
  <li><strong>Facebook:</strong> Settings &amp; privacy → Settings → Business integrations → Replyra → Remove.</li>
</ul>
<p>Replyra then loses access immediately; remaining data is deleted when we receive Meta's deletion notice or on your request.</p>

<h2>Option 3 — Email request</h2>
<p>
  Email <a href="mailto:admin@creativeshine.id">admin@creativeshine.id</a> with the subject
  <strong>"Replyra Data Deletion Request"</strong> and the Instagram username or Facebook Page involved. We verify the
  request, delete your data within <strong>30 days</strong>, and email you a confirmation.
</p>

<h2>What is deleted</h2>
<p>Account and workspace data, connected-account tokens, posts, comments, classifications and drafted replies. Records we must keep by law (e.g. invoices) are retained only as long as required.</p>
